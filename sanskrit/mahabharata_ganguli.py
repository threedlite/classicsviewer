def assign_ce_numbers(book, chapter_labels, report):
    """
    Map each DCS chapter label of a book to a critical-edition chapter number.

    Numeric labels are their own number. A run of non-numeric labels between
    two numeric neighbours takes the numbers missing between them when the
    counts agree (the Gita, labelled "BhaGi 1".."BhaGi 18" between 6.22 and
    6.41). Anything else is an error.
    """
    ce = [int(l) if re.fullmatch(r'\d+', l) else None for l in chapter_labels]
    i = 0
    while i < len(ce):
        if ce[i] is not None:
            i += 1
            continue
        j = i
        while j < len(ce) and ce[j] is None:
            j += 1
        prev_num = ce[i - 1] if i > 0 else None
        next_num = ce[j] if j < len(ce) else None
        if prev_num is None or next_num is None or next_num - prev_num - 1 != j - i:
            raise GanguliError(f'Book {book}: cannot number chapters {chapter_labels[i:j]} between {prev_num} and {next_num}')
        for k in range(i, j):
            ce[k] = prev_num + 1 + (k - i)
        report.append(f'Book {book}: chapters {chapter_labels[i:j]} numbered {ce[i]}-{ce[j - 1]} by position')
        i = j
    for a, b in zip(ce, ce[1:]):
        if b <= a:
            raise GanguliError(f'Book {book}: chapter numbers not increasing ({a} -> {b}); file order and labels disagree')
    return ce


def align_book(book, chapter_labels, rows, units, report):
    """
    Return [(unit_index, chapter_index_from, chapter_index_to, kind)] covering
    every chapter of the book, units in order.
    """
    ce_numbers = assign_ce_numbers(book, chapter_labels, report)
    index_of_ce = {n: i for i, n in enumerate(ce_numbers)}
    max_ce = max(ce_numbers)

    def chapter_index(n):
        """Index of CE chapter n; a chapter absent from DCS resolves to the nearest preceding one."""
        if n in index_of_ce:
            return index_of_ce[n]
        lower = [m for m in index_of_ce if m < n]
        if not lower:
            raise GanguliError(f'Book {book}: concordance refers to chapter {n} before any DCS chapter')
        report.append(f'Book {book}: critical-edition chapter {n} is not in DCS; its translation is attached to chapter {max(lower)}')
        return index_of_ce[max(lower)]

    # Known chapter indices per Ganguli numeral.
    known = defaultdict(set)
    last_roy = 0
    rejected = 0
    for r in rows:
        if r['r1'] is None:
            report.append(f'Book {book}: concordance row {r["printed"]!r} names no Ganguli section')
            continue
        if r['r1'] < last_roy:
            report.append(f'Book {book}: concordance row {r["printed"]!r} is out of order (after Ganguli {last_roy}) and is not used')
            rejected += 1
            continue
        last_roy = r['r2']
        chapters = list(range(r['c1'], r['c2'] + 1))
        sections = list(range(r['r1'], r['r2'] + 1))
        if len(chapters) == len(sections):
            for c, s in zip(chapters, sections):
                known[s].add(chapter_index(c))
        else:
            for s in sections:
                for c in chapters:
                    known[s].add(chapter_index(c))

    max_section = max(u['last'] for u in units)
    if last_roy > max_section:
        raise GanguliError(f'Book {book}: concordance refers to Ganguli section {last_roy} but the text has {max_section}')

    # Units with known chapters.
    spans = []
    for ui, u in enumerate(units):
        chs = set()
        for n in range(u['first'], u['last'] + 1):
            chs |= known.get(n, set())
        spans.append([ui, min(chs) if chs else None, max(chs) if chs else None, 'known' if chs else 'interval'])

    # Interval units: between nearest known neighbours.
    n_chapters = len(chapter_labels)
    for k, sp in enumerate(spans):
        if sp[3] == 'known':
            continue
        prev_end = next((spans[j][2] for j in range(k - 1, -1, -1) if spans[j][3] == 'known'), None)
        next_start = next((spans[j][1] for j in range(k + 1, len(spans)) if spans[j][3] == 'known'), None)
        sp[1] = prev_end if prev_end is not None else 0
        sp[2] = next_start if next_start is not None else n_chapters - 1

    # Chapters no unit covers: extend the neighbouring units to them.
    covered = set()
    for sp in spans:
        covered |= set(range(sp[1], sp[2] + 1))
    for ci in range(n_chapters):
        if ci in covered:
            continue
        prev_units = [sp for sp in spans if sp[2] < ci]
        next_units = [sp for sp in spans if sp[1] > ci]
        if not prev_units and not next_units:
            raise GanguliError(f'Book {book}: chapter {chapter_labels[ci]} cannot be covered')
        if prev_units:
            prev_units[-1][2] = ci
        if next_units:
            next_units[0][1] = ci
        report.append(f'Book {book}: no concordance row covers chapter {chapter_labels[ci]} '
                      f'(CE {ce_numbers[ci]}); the neighbouring sections are extended to it')

    # Validation.
    covered = set()
    for a, b in zip(spans, spans[1:]):
        if b[1] < a[1] or b[2] < a[2]:
            raise GanguliError(f'Book {book}: section spans cross: {a} then {b}')
    for sp in spans:
        if sp[1] is None or sp[2] is None or sp[1] > sp[2]:
            raise GanguliError(f'Book {book}: bad span {sp}')
        covered |= set(range(sp[1], sp[2] + 1))
    if covered != set(range(n_chapters)):
        raise GanguliError(f'Book {book}: chapters not covered: {sorted(set(range(n_chapters)) - covered)}')
    stats = {
        'units': len(spans),
        'one_chapter': sum(1 for sp in spans if sp[3] == 'known' and sp[1] == sp[2]),
        'several_chapters': sum(1 for sp in spans if sp[3] == 'known' and sp[1] != sp[2]),
        'interval': sum(1 for sp in spans if sp[3] == 'interval'),
        'rejected_rows': rejected,
        'chapters': n_chapters,
        'max_ce': max_ce,
    }
    return [tuple(sp) for sp in spans], stats


# ---------------------------------------------------------------------------
# Entry point for the build
# ---------------------------------------------------------------------------

def write_ganguli_translation(cursor, book_structure):
    """
    Write Ganguli segments for the Mahabharata.

    book_structure: {book_label: {'book_id': str, 'chapters': [(chapter_label, start_line, end_line), ...]}}
    in file order, as produced by write_parsed_work_to_db.

    Returns (segment_count, report_lines). Raises GanguliError on any
    inconsistency; the build must not continue past one.
    """
    report = []
    units_by_book = parse_ganguli(report)
    rows_by_book = load_concordance()

    labels = sorted(book_structure, key=lambda l: int(l))
    if [int(l) for l in labels] != list(range(1, 19)):
        raise GanguliError(f'DCS Mahabharata books {labels}, expected 1..18')

    total = 0
    for label in labels:
        b = int(label)
        info = book_structure[label]
        chapter_labels = [c[0] for c in info['chapters']]
        spans, stats = align_book(b, chapter_labels, rows_by_book[b], units_by_book[b], report)
        for ui, ci_from, ci_to, kind in spans:
            unit = units_by_book[b][ui]
            start_line = info['chapters'][ci_from][1]
            end_line = info['chapters'][ci_to][2]
            heading = (f'Section {unit["first"]}' if unit['first'] == unit['last']
                       else f'Sections {unit["first"]}-{unit["last"]}')
            cursor.execute('''
                INSERT INTO translation_segments (id, book_id, start_line, end_line, sequence_number, translation_text, translator, speaker)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            ''', (None, info['book_id'], start_line, end_line, start_line,
                  f'{heading}\n\n{unit["text"]}', TRANSLATOR, None))
            total += 1
        report.append(f'Book {b}: {stats["units"]} sections -> {stats["one_chapter"]} on one chapter, '
                      f'{stats["several_chapters"]} on a chapter run, {stats["interval"]} placed by interval; '
                      f'{stats["chapters"]} DCS chapters, CE max {stats["max_ce"]}; {stats["rejected_rows"]} rows rejected')
    expected = sum(len(u) for u in units_by_book.values())
    if total != expected:
        raise GanguliError(f'wrote {total} segments for {expected} section units')
    return total, report
