#!/usr/bin/env python3
"""
Kisari Mohan Ganguli's English translation of the Mahabharata (1883-1896),
attached chapter-exactly to the DCS critical-edition text.

Used by create_sanskrit_database_interlinear.py; not a standalone script.

Inputs (all under sanskrit/data-sources/):
  ganguli/pg15474.txt .. pg15477.txt   Project Gutenberg plain-text volumes,
                                       fetched by download_ganguli.sh when
                                       missing, verified by SHA-256 of the
                                       text between the Gutenberg markers.
  mbh_ce_ganguli_concordance.csv       Critical edition -> Ganguli section
                                       table, generated by
                                       extract_mbh_concordance.py.

Alignment rule (sanskrit/MAHABHARATA_GANGULI_PROPOSAL.md, section 5.2):
a Ganguli section is attached to the critical-edition chapters the
published concordance pairs it with. A section the concordance pairs with
a verse range of a chapter is attached to that whole chapter, so a section
that straddles two chapters is attached to both. A section the concordance
does not mention is attached to the run of chapters between its nearest
mentioned neighbours. A chapter no section is attached to is covered by
extending the neighbouring sections to it. Nothing is scored or guessed;
every section is written exactly once; every chapter is covered.

Ganguli section headings: Books 1-7 and 12-15 use "SECTION <roman>", Books
8-11 and 16-18 a bare arabic number on its own line. Headings missing from
the Gutenberg transcription (Ganguli 1.177, 2.67, 7.54, 7.55, 7.189, 12.34,
12.35, 12.364) leave their text inside the preceding section; that unit is
then attached to the chapters of every numeral it contains. Footnotes are
numbered per book, referenced inline as [n] and listed after "FOOTNOTES" at
the end of the book; they are appended to the section that cites them.
"""

import csv
import hashlib
import os
import re
import subprocess
from collections import defaultdict

TRANSLATOR = 'Kisari Mohan Ganguli'
DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data-sources')
GANGULI_DIR = os.path.join(DATA_DIR, 'ganguli')
CONCORDANCE_CSV = os.path.join(DATA_DIR, 'mbh_ce_ganguli_concordance.csv')
DOWNLOAD_SCRIPT = os.path.join(DATA_DIR, 'download_ganguli.sh')

# (Gutenberg number, books, SHA-256 of the UTF-8 text between the
# "*** START OF" line and the "*** END OF" line, newlines normalised to \n).
VOLUMES = [
    (15474, (1, 2, 3), '355bd154573d3d2d9032e5dbf61b7cddd0f74ebbd36c372670d32e8679c23812'),
    (15475, (4, 5, 6, 7), 'e81d9d42473d52a349f8b473ab1bf04831ef641d3ba6a807d5ef408822f79055'),
    (15476, (8, 9, 10, 11, 12), 'e9128f75b38130ddaf3d807adb2c9006a7f6c7c225ff3b2336ba41ed2bab0d26'),
    (15477, (13, 14, 15, 16, 17, 18), 'b1cedd78362dee48f8ed608be20541866f89156fda3403aa841c3c99b816475c'),
]

BOOK_RE = re.compile(r'^\s*BOOK (\d+)\s*$')
ROMAN_HEADING_RE = re.compile(r'^\s*SECTION ([IVXLCDM]+)\s*$')
ARABIC_HEADING_RE = re.compile(r'^\s*(\d{1,3})\s*$')
FOOTNOTES_RE = re.compile(r'^\s*FOOTNOTES\s*$')
NOTE_START_RE = re.compile(r'^\s*(\d+)\.\s+(.*)$')
MARKER_RE = re.compile(r'\[(\d+)\]')


class GanguliError(Exception):
    pass


def roman_to_int(s):
    values = {'I': 1, 'V': 5, 'X': 10, 'L': 50, 'C': 100, 'D': 500, 'M': 1000}
    total, prev = 0, 0
    for ch in reversed(s):
        n = values[ch]
        total = total - n if n < prev else total + n
        prev = max(prev, n)
    return total


# ---------------------------------------------------------------------------
# Gutenberg texts
# ---------------------------------------------------------------------------

def load_gutenberg_bodies():
    """Return {book_number: text} for Books 1-18, after fetching and verifying the volumes."""
    missing = [n for n, _, _ in VOLUMES if not os.path.isfile(os.path.join(GANGULI_DIR, f'pg{n}.txt'))]
    if missing:
        print(f'  Ganguli volumes missing ({missing}); running {os.path.basename(DOWNLOAD_SCRIPT)}')
        subprocess.run(['bash', DOWNLOAD_SCRIPT], check=True)

    books = {}
    for number, book_numbers, sha in VOLUMES:
        path = os.path.join(GANGULI_DIR, f'pg{number}.txt')
        with open(path, 'rb') as f:
            raw = f.read()
        text = raw.decode('utf-8-sig').replace('\r\n', '\n')
        starts = [m.start() for m in re.finditer(r'^\*\*\* START OF', text, re.M)]
        ends = [m.start() for m in re.finditer(r'^\*\*\* END OF', text, re.M)]
        if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
            raise GanguliError(f'{path}: expected one START and one END marker, found {len(starts)} and {len(ends)}')
        body = text[text.index('\n', starts[0]) + 1:ends[0]]
        digest = hashlib.sha256(body.encode('utf-8')).hexdigest()
        if digest != sha:
            raise GanguliError(f'{path}: content hash {digest} does not match the recorded {sha}; '
                               f'the Gutenberg text has changed, re-check it and update VOLUMES')
        # Split the volume at its BOOK headings.
        lines = body.split('\n')
        heads = [(i, int(BOOK_RE.match(l).group(1))) for i, l in enumerate(lines) if BOOK_RE.match(l)]
        if [b for _, b in heads] != list(book_numbers):
            raise GanguliError(f'{path}: BOOK headings {[b for _, b in heads]}, expected {list(book_numbers)}')
        # Each BOOK heading is preceded by the title block ("The Mahabharata /
        # of / Krishna-Dwaipayana Vyasa"); a book's lines run from its heading
        # to the start of the next book's title block, so that the title of
        # the next book does not trail the footnotes of this one.
        cuts = []
        for i, b in heads:
            j = i
            for k in range(i - 1, max(i - 8, -1), -1):
                if lines[k].strip() == 'The Mahabharata':
                    j = k
                    break
            cuts.append((i, j, b))
        for (i, _, b), nxt in zip(cuts, cuts[1:] + [(len(lines), len(lines), None)]):
            books[b] = lines[i + 1:nxt[1]]
    if sorted(books) != list(range(1, 19)):
        raise GanguliError(f'books found: {sorted(books)}')
    return books


def reflow(lines):
    """Join hard-wrapped lines into paragraphs separated by blank lines."""
    paras, cur = [], []
    for l in lines:
        if l.strip():
            cur.append(l.strip())
        elif cur:
            paras.append(' '.join(cur))
            cur = []
    if cur:
        paras.append(' '.join(cur))
    return '\n\n'.join(paras)


def parse_book(book, lines, report):
    """
    Split one book into section units with footnotes resolved.

    Returns a list of dicts: first, last (Ganguli numerals the unit covers),
    text (prose plus appended footnotes).
    """
    # Headings: roman "SECTION n" if the book has any, else bare arabic numbers.
    roman = [(i, roman_to_int(m.group(1))) for i, l in enumerate(lines) for m in [ROMAN_HEADING_RE.match(l)] if m]
    foot_idx = next((i for i, l in enumerate(lines) if FOOTNOTES_RE.match(l)), None)
    if roman:
        heads = roman
    else:
        heads = [(i, int(m.group(1))) for i, l in enumerate(lines) for m in [ARABIC_HEADING_RE.match(l)] if m
                 and (foot_idx is None or i < foot_idx)]
    if not heads:
        raise GanguliError(f'Book {book}: no section headings found')
    if foot_idx is not None:
        heads = [(i, n) for i, n in heads if i < foot_idx]
    numerals = [n for _, n in heads]
    if numerals[0] != 1:
        raise GanguliError(f'Book {book}: first section numeral is {numerals[0]}')
    for a, b in zip(numerals, numerals[1:]):
        if b <= a:
            raise GanguliError(f'Book {book}: section numerals not increasing at {a} -> {b}')
    skipped = [n for n in range(1, numerals[-1] + 1) if n not in numerals]
    if skipped:
        report.append(f'Book {book}: section headings {skipped} missing from the transcription; '
                      f'their text stays with the preceding section')

    front = sum(1 for l in lines[:heads[0][0]] if l.strip())
    if front:
        report.append(f'Book {book}: {front} non-blank front-matter lines before the first section are not translation text and are not loaded')

    # Footnotes of the book.
    notes = {}
    if foot_idx is not None:
        cur_num, cur_lines, orphans = None, [], []
        for l in lines[foot_idx + 1:]:
            m = NOTE_START_RE.match(l)
            if m:
                if cur_num is not None:
                    notes.setdefault(cur_num, []).append(' '.join(cur_lines))
                cur_num, cur_lines = int(m.group(1)), [m.group(2).strip()]
            elif cur_num is not None:
                # A note may run over several paragraphs; it ends only at the
                # next numbered note (the book was cut before the next book's
                # title block, so nothing else follows the notes).
                if l.strip():
                    cur_lines.append(l.strip())
                elif cur_lines and cur_lines[-1] != '\n':
                    cur_lines.append('\n')
            elif l.strip():
                orphans.append(l.strip())
        if cur_num is not None:
            notes.setdefault(cur_num, []).append(' '.join(cur_lines))
        for k in notes:
            notes[k] = [re.sub(r' ?\n ?', '\n', t).strip() for t in notes[k]]
        if orphans:
            raise GanguliError(f'Book {book}: {len(orphans)} lines after the footnotes belong to no note: {orphans[:5]}')
    dup_notes = {n: len(v) for n, v in notes.items() if len(v) > 1}
    if dup_notes:
        report.append(f'Book {book}: footnote numbers listed more than once {dup_notes}; all texts are kept')

    # Section units.
    end_of_text = foot_idx if foot_idx is not None else len(lines)
    units = []
    seen_markers = defaultdict(int)
    for (i, n), nxt in zip(heads, heads[1:] + [(end_of_text, None)]):
        body_lines = lines[i + 1:nxt[0]]
        last = (nxt[1] - 1) if nxt[1] is not None else n
        text = reflow(body_lines)
        cited = []
        for m in MARKER_RE.finditer(text):
            k = int(m.group(1))
            if k not in notes:
                raise GanguliError(f'Book {book}: footnote marker [{k}] in section {n} has no footnote text')
            if k not in cited:
                cited.append(k)
            seen_markers[k] += 1
        for k in cited:
            for t in notes[k]:
                text += f'\n\n[{k}] {t}'
        units.append({'first': n, 'last': last, 'text': text})
    dup_markers = sorted(k for k, c in seen_markers.items() if c > 1)
    if dup_markers:
        report.append(f'Book {book}: footnote markers used more than once {dup_markers}; the note is shown at each use')
    unreferenced = sorted(k for k in notes if k not in seen_markers)
    if unreferenced:
        report.append(f'Book {book}: footnotes {unreferenced} are cited nowhere; appended to the last section')
        for k in unreferenced:
            for t in notes[k]:
                units[-1]['text'] += f'\n\n[{k}] {t}'
    return units


def parse_ganguli(report):
    books = load_gutenberg_bodies()
    return {b: parse_book(b, books[b], report) for b in sorted(books)}


