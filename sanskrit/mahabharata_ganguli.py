def load_concordance():
    if not os.path.isfile(CONCORDANCE_CSV):
        raise GanguliError(f'{CONCORDANCE_CSV} missing; generate it with data-sources/extract_mbh_concordance.py')
    rows = defaultdict(list)
    with open(CONCORDANCE_CSV, encoding='utf-8') as f:
        reader = csv.DictReader(l for l in f if not l.startswith('#'))
        for r in reader:
            rows[int(r['book'])].append({
                'c1': int(r['ce_chapter_from']), 'c2': int(r['ce_chapter_to']),
                'v1': int(r['ce_verse_from']) if r['ce_verse_from'] else None,
                'r1': int(r['ganguli_from']) if r['ganguli_from'] else None,
                'r2': int(r['ganguli_to']) if r['ganguli_to'] else None,
                'printed': r['printed'],
            })
    if sorted(rows) != list(range(1, 19)):
        raise GanguliError(f'concordance covers books {sorted(rows)}')
    for b, rs in rows.items():
        if rs[0]['c1'] != 1:
            raise GanguliError(f'concordance book {b} starts at chapter {rs[0]["c1"]}')
        for p, c in zip(rs, rs[1:]):
            if c['c1'] not in (p['c2'], p['c2'] + 1):
                raise GanguliError(f'concordance book {b}: gap or overlap between {p["printed"]!r} and {c["printed"]!r}')
    return rows


